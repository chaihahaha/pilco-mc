"""Measure how far the model can be imagined before the rollout stops being true.

This is the diagnostic that decides whether particle-based planning with a
learned network can work at all, and it is the one experiment that explains the
result in the README.

It fits the dynamics ensemble on data generated by a *known-good* swing-up
controller, then compares, for increasing horizon ``H``:

* the cost the model **imagines** for that controller from the initial belief;
* the cost the controller **actually** pays on the true system.

If the two agree up to some ``H`` and then separate, the model is fine one step
at a time and the imagination has simply drifted: no amount of policy
optimisation can fix that, because the optimiser is optimising the wrong
trajectory.

The good controller comes from ``../pilco_pytorch``; without it the script falls
back to a random controller (much less informative).

Usage::

    python scripts/diagnose_imagination.py
"""
from __future__ import annotations

import importlib.util
import os
import sys

import numpy as np
import torch

_HERE = os.path.dirname(os.path.abspath(__file__))
_ROOT = os.path.dirname(_HERE)
sys.path.insert(0, _ROOT)

torch.set_default_dtype(torch.float64)

from pilco_mc import MCConfig, fit_model, make_cartpole            # noqa: E402
from pilco_mc.objective import cost_statistics                     # noqa: E402
from pilco_mc.particles import initial_particles, rollout          # noqa: E402

_CONTROLLER = os.path.join(os.path.dirname(_ROOT), "pilco_pytorch", "results",
                           "cartpole_swingup_policy.npz")


def load_controller():
    """The 12.8-cost swing-up controller trained by ``pilco_pytorch``."""
    if not os.path.exists(_CONTROLLER):
        return None
    spec = importlib.util.spec_from_file_location(
        "anim", os.path.join(os.path.dirname(_ROOT), "pilco_pytorch", "scripts",
                             "make_animation.py"))
    anim = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(anim)
    return anim.Controller(_CONTROLLER)


class ControllerPolicy(torch.nn.Module):
    """Wrap the numpy controller as a ``(B, D) -> (B, 1)`` torch policy."""

    def __init__(self, control):
        super().__init__()
        self.control = control

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        with torch.no_grad():
            return torch.as_tensor(
                [[np.clip(self.control(v.numpy()), -10.0, 10.0)] for v in x])


def main() -> int:
    control = load_controller()
    if control is None:
        print(f"controller not found at {_CONTROLLER}; using random actions instead")
    scenario = make_cartpole()
    rng = np.random.default_rng(0)

    # ---- data from the good controller -----------------------------------
    states, controls, deltas = [], [], []
    for _ in range(4):
        x = np.zeros(4)
        s, u = [], []
        for _ in range(100):
            a = float(np.clip(control(x), -10, 10)) if control else \
                float(rng.uniform(-10, 10))
            u.append(a)
            s.append(x.copy())
            x = scenario.step_true(x, a) + rng.standard_normal(4) * scenario.process_noise
        s.append(x.copy())
        i, j, k = scenario.transitions(np.asarray(s), np.asarray(u))
        states.append(i)
        controls.append(j)
        deltas.append(k)
    states, controls, deltas = (torch.cat(v) for v in (states, controls, deltas))

    model = fit_model(states, controls, deltas, MCConfig(verbose=False), seed=0)
    with torch.no_grad():
        pred, _ = model.predict(states, controls)
        r2 = 1 - ((deltas - pred) ** 2).sum() / ((deltas - deltas.mean(0)) ** 2).sum()
    print(f"one-step fit: R^2 = {float(r2):.3f} on {states.shape[0]} transitions\n")

    if control is None:
        print("without a good controller this comparison is not meaningful")
        return 0

    policy = ControllerPolicy(control)
    gen = torch.Generator().manual_seed(0)
    particles = initial_particles(torch.zeros(4), torch.eye(4) * 0.01, 64, gen)
    roll = rollout(policy, model, particles, 40, gen)

    print(f"{'H':>3}  {'imagined':>9}  {'true':>7}   ratio")
    for horizon in (5, 10, 15, 20, 30, 40):
        window = type(roll)(roll.states[:horizon + 1], roll.controls[:horizon],
                            roll.variances[:horizon])
        imagined, _ = cost_statistics(window, scenario.cost)
        true_costs = []
        for _ in range(8):
            x, total = np.zeros(4), 0.0
            for _ in range(horizon):
                total += float(scenario.cost(torch.as_tensor(x)))
                x = scenario.step_true(x, float(np.clip(control(x), -10, 10)))
            true_costs.append(total)
        true = float(np.mean(true_costs))
        print(f"{horizon:3d}  {imagined:9.2f}  {true:7.2f}   {imagined / max(true, 1e-9):5.1f}x")
    print("\nThe 1:1 agreement up to H=10 and the blow-up after it is the whole")
    print("story: a one-step-trained network is a valid model, but its imagined")
    print("trajectory drifts off the data after about ten steps, and the cost of")
    print("the drifted trajectory is ~1 per step (the pole has fallen).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
